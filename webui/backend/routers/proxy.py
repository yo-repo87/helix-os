"""
Reverse proxy route management (nginx-based).

GET    /api/proxy/routes          — list routes
POST   /api/proxy/routes          — create route
PUT    /api/proxy/routes/{id}     — update route
DELETE /api/proxy/routes/{id}     — delete route
POST   /api/proxy/apply           — write nginx configs + reload
GET    /api/proxy/status          — nginx status
"""

import json
import os
import re
import secrets
import subprocess
from pathlib import Path

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

from config import HELIX_CONFIG

router = APIRouter(prefix="/api/proxy", tags=["proxy"])

ROUTES_FILE  = os.path.join(HELIX_CONFIG, "proxy_routes.json")
NGINX_CONF_D = "/etc/nginx/conf.d"
HELIX_PROXY   = os.path.join(NGINX_CONF_D, "helix-proxy.conf")


# ── Persistence ───────────────────────────────────────────────────

def _load_routes() -> list[dict]:
    try:
        return json.loads(Path(ROUTES_FILE).read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return []

def _save_routes(routes: list[dict]):
    Path(ROUTES_FILE).parent.mkdir(parents=True, exist_ok=True)
    Path(ROUTES_FILE).write_text(json.dumps(routes, indent=2))


# ── Schemas ───────────────────────────────────────────────────────

class RouteCreate(BaseModel):
    domain:         str          # e.g. jellyfin.local or jellyfin.example.com
    upstream:       str          # e.g. localhost:8096 or 192.168.1.10:8096
    ssl:            bool = False
    websocket:      bool = False  # upgrade headers
    custom_headers: str  = ""    # extra proxy_set_header lines (newline-separated)
    enabled:        bool = True

class RouteUpdate(RouteCreate):
    pass


# ── Nginx config generation ───────────────────────────────────────

def _gen_location(route: dict) -> str:
    ws_block = ""
    if route.get("websocket"):
        ws_block = """
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";"""

    custom = ""
    for line in (route.get("custom_headers") or "").splitlines():
        line = line.strip()
        if line:
            custom += f"\n        {line};"

    return f"""
    location / {{
        proxy_pass http://{route['upstream']};
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;{ws_block}{custom}
        proxy_read_timeout 300s;
        proxy_connect_timeout 10s;
    }}"""


def _gen_server_block(route: dict) -> str:
    domain = route["domain"]
    ssl_block = ""
    listen_port = "80"
    if route.get("ssl"):
        cert = f"/etc/helix/ssl/helix.crt"
        key  = f"/etc/helix/ssl/helix.key"
        # Per-domain cert if exists
        dc = f"/etc/helix/ssl/{domain}.crt"
        dk = f"/etc/helix/ssl/{domain}.key"
        if Path(dc).exists() and Path(dk).exists():
            cert, key = dc, dk
        ssl_block = f"""
    listen 443 ssl;
    ssl_certificate {cert};
    ssl_certificate_key {key};
    ssl_session_cache shared:SSL:1m;"""
        listen_port = "80"

    return f"""
# helix-proxy: {route['id']} — {domain}
server {{
    listen {listen_port};{ssl_block}
    server_name {domain};
    {_gen_location(route)}
}}"""


def _write_nginx_conf(routes: list[dict]):
    enabled = [r for r in routes if r.get("enabled", True)]
    conf = "# Generated by Helix OS reverse proxy manager — do not edit manually\n"
    for r in enabled:
        conf += _gen_server_block(r)
    Path(NGINX_CONF_D).mkdir(parents=True, exist_ok=True)
    Path(HELIX_PROXY).write_text(conf)


def _nginx(*args: str) -> subprocess.CompletedProcess:
    """Run nginx as root. The backend is the unprivileged helix user, and even
    `nginx -t` opens /run/nginx.pid for writing, so it fails without sudo."""
    cmd = ["nginx", *args]
    if os.geteuid() != 0:
        cmd = ["sudo", "-n", *cmd]
    return subprocess.run(cmd, capture_output=True, text=True)


def _nginx_reload() -> tuple[bool, str]:
    # Test config first
    r = _nginx("-t")
    if r.returncode != 0:
        return False, r.stderr
    r2 = _nginx("-s", "reload")
    return r2.returncode == 0, r2.stderr or "ok"


# ── Endpoints ─────────────────────────────────────────────────────

@router.get("/routes")
def list_routes():
    return _load_routes()


@router.post("/routes")
def create_route(req: RouteCreate):
    routes = _load_routes()
    # Validate domain is sane
    if not re.match(r'^[a-zA-Z0-9._*-]+$', req.domain):
        raise HTTPException(400, "Invalid domain format")
    route = req.model_dump()
    route["id"] = secrets.token_hex(5)
    routes.append(route)
    _save_routes(routes)
    return route


@router.put("/routes/{route_id}")
def update_route(route_id: str, req: RouteUpdate):
    routes = _load_routes()
    for i, r in enumerate(routes):
        if r["id"] == route_id:
            updated = req.model_dump()
            updated["id"] = route_id
            routes[i] = updated
            _save_routes(routes)
            return updated
    raise HTTPException(404, "Route not found")


@router.delete("/routes/{route_id}")
def delete_route(route_id: str):
    routes = [r for r in _load_routes() if r["id"] != route_id]
    _save_routes(routes)
    return {"ok": True}


@router.post("/apply")
def apply_routes():
    routes = _load_routes()
    try:
        _write_nginx_conf(routes)
    except Exception as e:
        raise HTTPException(500, f"Config write failed: {e}")
    ok, msg = _nginx_reload()
    return {"ok": ok, "message": msg}


@router.get("/status")
def proxy_status():
    r = _nginx("-t")
    r2 = subprocess.run(["pgrep", "-x", "nginx"], capture_output=True)
    return {
        "running": r2.returncode == 0,
        "config_ok": r.returncode == 0,
        "config_error": r.stderr.strip() if r.returncode != 0 else None,
        "conf_path": HELIX_PROXY,
    }
