#!/bin/bash
# setup-test-array.sh — Create a simulated Helix OS array using loop devices.
#
# Creates 4 sparse image files (3 data + 1 parity), attaches them as loop
# devices, formats the data drives as XFS, then runs the full array start
# sequence to prove the system works without real hardware.
#
# Usage: sudo ./setup-test-array.sh
# Cleanup: sudo ./teardown-test-array.sh

set -euo pipefail

[[ $EUID -eq 0 ]] || { echo "Must run as root (sudo $0)"; exit 1; }

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ARRAY_SBIN="$SCRIPT_DIR/../sbin"
IMG_DIR="/tmp/helix-test-imgs"
TEST_CFG="/tmp/helix-test-config"
DATA_SIZE_MB=512   # each data disk: 512 MB
PARITY_SIZE_MB=512 # parity disk must be >= largest data disk

echo "════════════════════════════════════════════════════════"
echo " Helix OS — Test Array Setup"
echo " Image dir:   $IMG_DIR"
echo " Data disks:  3 × ${DATA_SIZE_MB}MB"
echo " Parity disk: 1 × ${PARITY_SIZE_MB}MB"
echo "════════════════════════════════════════════════════════"
echo ""

# ── Create image files ────────────────────────────────────────────────────────
mkdir -p "$IMG_DIR" "$TEST_CFG"

echo "Creating sparse disk images..."
for n in 1 2 3; do
    IMG="$IMG_DIR/disk${n}.img"
    [ -f "$IMG" ] || truncate -s "${DATA_SIZE_MB}M" "$IMG"
    echo "  disk$n: $IMG"
done
PARITY_IMG="$IMG_DIR/parity1.img"
[ -f "$PARITY_IMG" ] || truncate -s "${PARITY_SIZE_MB}M" "$PARITY_IMG"
echo "  parity1: $PARITY_IMG"

# ── Attach loop devices ───────────────────────────────────────────────────────
echo ""
echo "Attaching loop devices..."

attach_loop() {
    local img="$1"
    local existing
    existing=$(losetup -j "$img" 2>/dev/null | cut -d: -f1 | head -1)
    if [ -n "$existing" ]; then
        echo "  $img → $existing (already attached)"
        echo "$existing"
    else
        local dev
        dev=$(losetup --find --show --sector-size 512 "$img")
        echo "  $img → $dev"
        echo "$dev"
    fi
}

DISK1_DEV=$(attach_loop "$IMG_DIR/disk1.img")
DISK2_DEV=$(attach_loop "$IMG_DIR/disk2.img")
DISK3_DEV=$(attach_loop "$IMG_DIR/disk3.img")
PARITY_DEV=$(attach_loop "$IMG_DIR/parity1.img")

# ── Format data drives as XFS ─────────────────────────────────────────────────
echo ""
echo "Formatting data drives as XFS..."
for dev in "$DISK1_DEV" "$DISK2_DEV" "$DISK3_DEV"; do
    if blkid "$dev" &>/dev/null; then
        echo "  $dev already has a filesystem — skipping format."
    else
        mkfs.xfs -f "$dev" > /dev/null
        echo "  $dev → XFS"
    fi
done
echo "  $PARITY_DEV → (raw, no filesystem — SnapRAID uses it directly)"

# ── Write test disks.cfg ──────────────────────────────────────────────────────
echo ""
echo "Writing test disks.cfg..."
cat > "$TEST_CFG/disks.cfg" <<EOF
# Test array config — auto-generated by setup-test-array.sh
# Devices: loop devices backed by sparse image files

[parity1]
device=$PARITY_DEV

[disk1]
device=$DISK1_DEV
format=xfs

[disk2]
device=$DISK2_DEV
format=xfs

[disk3]
device=$DISK3_DEV
format=xfs

[sharedefaults]
included_disks=all
allocation=most_free
split_level=1
EOF

# Write test shares.cfg
cat > "$TEST_CFG/shares.cfg" <<EOF
[media]
comment=Test media share
included_disks=all
allocation=most_free
split_level=2
smb=no
nfs=no

[downloads]
comment=Test downloads
included_disks=disk1,disk2
allocation=most_free
split_level=1
smb=no
nfs=no
EOF

echo "  $TEST_CFG/disks.cfg"
echo "  $TEST_CFG/shares.cfg"

# ── Run helix-array-start against the test config ─────────────────────────────
echo ""
echo "Starting test array..."
HELIX_CONFIG="$TEST_CFG" bash "$ARRAY_SBIN/helix-array-start"

# ── Create some test files to populate the array ─────────────────────────────
echo ""
echo "Creating test files in /mnt/user/..."
mkdir -p /mnt/user/media/movies /mnt/user/media/music /mnt/user/downloads
dd if=/dev/urandom bs=1M count=10 2>/dev/null | dd of=/mnt/user/media/movies/test-movie.mkv bs=1M 2>/dev/null
dd if=/dev/urandom bs=1M count=5  2>/dev/null | dd of=/mnt/user/downloads/test-download.bin bs=1M 2>/dev/null
echo "  Created 10MB test-movie.mkv, 5MB test-download.bin"

# ── Sync parity ───────────────────────────────────────────────────────────────
echo ""
echo "Syncing parity (SnapRAID)..."
HELIX_CONFIG="$TEST_CFG" bash "$ARRAY_SBIN/helix-parity-check"

# ── Show status ───────────────────────────────────────────────────────────────
echo ""
echo "════════════════════════════════════════════════════════"
echo " Test Array Status:"
echo ""
HELIX_CONFIG="$TEST_CFG" bash "$ARRAY_SBIN/helix-array-status"
echo ""
echo "════════════════════════════════════════════════════════"
echo " Test array is running!"
echo ""
echo " User share:  /mnt/user/"
echo " Disk mounts: /mnt/disk1  /mnt/disk2  /mnt/disk3"
echo " Config:      $TEST_CFG"
echo ""
echo " To tear down: sudo ./teardown-test-array.sh"
echo "════════════════════════════════════════════════════════"
