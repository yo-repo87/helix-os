"""
FTP server configuration (vsftpd).

GET  /api/ftp/config    — current settings
PUT  /api/ftp/config    — save and apply
GET  /api/ftp/status    — running / not running
POST /api/ftp/start     — start vsftpd
POST /api/ftp/stop      — stop vsftpd
"""

import os
import subprocess
from pathlib import Path

from fastapi import APIRouter
from pydantic import BaseModel

from config import HELIX_CONFIG

router = APIRouter(prefix="/api/ftp", tags=["ftp"])

CFG_FILE     = os.path.join(HELIX_CONFIG, "ftp.cfg")
VSFTPD_CONF  = "/etc/vsftpd.conf"


def _run(*args, timeout: int = 10) -> tuple[int, str]:
    try:
        r = subprocess.run(["sudo", "-n"] + list(args),
                           capture_output=True, text=True, timeout=timeout)
        return r.returncode, r.stdout + r.stderr
    except (FileNotFoundError, subprocess.TimeoutExpired) as e:
        return 1, str(e)


def _load_cfg() -> dict:
    defaults = {
        "enabled":          "false",
        "port":             "21",
        "allow_anonymous":  "false",
        "anon_root":        "/mnt/user",
        "local_users":      "true",
        "write_enable":     "true",
        "chroot_local":     "true",
        "passive_min_port": "60000",
        "passive_max_port": "60100",
        "banner":           "Welcome to Helix OS FTP",
    }
    try:
        for line in Path(CFG_FILE).read_text().splitlines():
            line = line.strip()
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                defaults[k.strip()] = v.strip()
    except FileNotFoundError:
        pass
    defaults["enabled"]         = defaults["enabled"].lower() in ("true", "1", "yes")
    defaults["allow_anonymous"] = defaults["allow_anonymous"].lower() in ("true", "1", "yes")
    defaults["local_users"]     = defaults["local_users"].lower() in ("true", "1", "yes")
    defaults["write_enable"]    = defaults["write_enable"].lower() in ("true", "1", "yes")
    defaults["chroot_local"]    = defaults["chroot_local"].lower() in ("true", "1", "yes")
    return defaults


def _save_cfg(d: dict):
    Path(CFG_FILE).parent.mkdir(parents=True, exist_ok=True)
    lines = []
    for k, v in d.items():
        if isinstance(v, bool):
            lines.append(f"{k}={'true' if v else 'false'}")
        else:
            lines.append(f"{k}={v}")
    Path(CFG_FILE).write_text("\n".join(lines) + "\n")


def _write_vsftpd(cfg: dict):
    """Generate /etc/vsftpd.conf from our config."""
    yes_no = lambda v: "YES" if v else "NO"
    conf = f"""# Generated by Helix OS — do not edit manually
listen=YES
listen_ipv6=NO
listen_port={cfg.get('port', 21)}
anonymous_enable={yes_no(cfg.get('allow_anonymous', False))}
anon_root={cfg.get('anon_root', '/mnt/user')}
local_enable={yes_no(cfg.get('local_users', True))}
write_enable={yes_no(cfg.get('write_enable', True))}
local_umask=022
local_root=/mnt/user
xferlog_enable=YES
xferlog_std_format=NO
log_ftp_protocol=YES
vsftpd_log_file=/var/log/vsftpd.log
guest_enable={yes_no(cfg.get('local_users', True))}
guest_username=helix
virtual_use_local_privs=YES
no_anon_password=YES
hide_ids=YES
chroot_local_user=YES
allow_writeable_chroot=YES
pasv_enable=YES
pasv_min_port={cfg.get('passive_min_port', 60000)}
pasv_max_port={cfg.get('passive_max_port', 60100)}
ftpd_banner={cfg.get('banner', 'Welcome')}
secure_chroot_dir=/var/run/vsftpd/empty
pam_service_name=vsftpd
"""
    # Write via tee
    import subprocess
    r = subprocess.run(
        ["sudo", "-n", "tee", VSFTPD_CONF],
        input=conf, capture_output=True, text=True, timeout=10)
    return r.returncode == 0


# ── Endpoints ─────────────────────────────────────────────────────

class FtpCfg(BaseModel):
    enabled: bool = False
    port: int = 21
    allow_anonymous: bool = False
    anon_root: str = "/mnt/user"
    local_users: bool = True
    write_enable: bool = True
    chroot_local: bool = True
    passive_min_port: int = 60000
    passive_max_port: int = 60100
    banner: str = "Welcome to Helix OS FTP"


@router.get("/config")
def get_config():
    return _load_cfg()


def _installed() -> bool:
    import shutil
    return shutil.which("vsftpd") is not None or os.path.exists("/usr/sbin/vsftpd")


def _listening(port: int) -> bool:
    import socket
    try:
        with socket.create_connection(("127.0.0.1", int(port)), timeout=2):
            return True
    except OSError:
        return False


def _apply(cfg: dict) -> dict:
    """Write vsftpd.conf and start/stop the service. Returns {ok, error, active}; never claims success it did not verify."""
    if not _installed():
        return {"ok": False, "active": False, "error": "The FTP server (vsftpd) is not installed on this system. Update Helix OS to a version that includes it."}
    if not _write_vsftpd(cfg):
        return {"ok": False, "active": False, "error": "Could not write /etc/vsftpd.conf."}
    if not cfg["enabled"]:
        _run("systemctl", "disable", "--now", "vsftpd")
        return {"ok": True, "active": False}
    rc, out = _run("systemctl", "enable", "--now", "vsftpd")
    _run("systemctl", "restart", "vsftpd")           # --now does not restart a service that is already running with old settings
    import time
    for _ in range(10):
        if _listening(cfg["port"]):
            return {"ok": True, "active": True}
        time.sleep(0.5)
    _, log = _run("journalctl", "-u", "vsftpd", "-n", "5", "--no-pager")
    return {"ok": False, "active": False, "error": f"vsftpd did not start listening on port {cfg['port']}. {log.strip()[-300:]}"}


def apply_saved() -> None:
    """Called when the backend starts: the root file system is RAM, so /etc/vsftpd.conf and the enabled service are gone after a reboot."""
    try:
        cfg = _load_cfg()
        if cfg.get("enabled"):
            _apply(cfg)
    except Exception:                                  # noqa: BLE001 - boot must not fail because of FTP
        pass


@router.put("/config")
def put_config(req: FtpCfg):
    cfg = req.dict()
    if not (1 <= cfg["port"] <= 65535) or not (1024 <= cfg["passive_min_port"] <= cfg["passive_max_port"] <= 65535):
        return {"ok": False, "error": "Ports must be 1-65535, and the passive range 1024-65535 with min not above max."}
    if not cfg["anon_root"].startswith("/mnt/") or ".." in cfg["anon_root"].split("/"):
        return {"ok": False, "error": "The anonymous folder must be inside /mnt (for example /mnt/user)."}
    _save_cfg(cfg)
    return _apply(cfg)


@router.get("/log")
def ftp_log(lines: int = 60):
    """Recent FTP commands and replies (logins, 530 rejections ...), so a refused connection can be explained."""
    rc, out = _run("tail", "-n", str(max(10, min(lines, 300))), "/var/log/vsftpd.log")
    return {"lines": out.splitlines() if rc == 0 else [], "note": "" if rc == 0 else "No FTP log yet: it starts with the first connection."}


@router.get("/status")
def ftp_status():
    rc, out = _run("systemctl", "is-active", "vsftpd")
    cfg = _load_cfg()
    return {"active": rc == 0, "state": out.strip(), "installed": _installed(), "port": cfg["port"], "listening": _listening(cfg["port"]),
            "anonymous": cfg["allow_anonymous"], "local_users": cfg["local_users"]}


@router.post("/start")
def ftp_start():
    rc, out = _run("systemctl", "start", "vsftpd")
    return {"ok": rc == 0, "output": out.strip()}


@router.post("/stop")
def ftp_stop():
    rc, out = _run("systemctl", "stop", "vsftpd")
    return {"ok": rc == 0, "output": out.strip()}
